#!/usr/bin/env node
// LOCAL-FIRST browser AI (package lf-e11): writes src/lib/local-first/ai/__fixtures__/live-registry-contract.ts, the
// fixture registry-contract.test.ts checks every laptop write against.
//
// Usage: node scripts/vendor-ai-registry-contract.mjs <path to compliance-tracker checkout> [git ref, default HEAD]
//
// WHAT IT COPIES. From compliance-tracker at that ref:
//   * supabase/functions/ai-work-link/function-registry.generated.json -- every function id (reads included) and, for
//     each WRITE, the parameter names the live pipeline declares and requires (generated from
//     src/lib/pipeline/function-registry.ts by scripts/gen-ai-link-registry.ts);
//   * the line of src/lib/pipeline/function-registry.ts that declares each write (`functionId: "<id>"`), written next to
//     it as a comment, so a reviewer can open the real spec in one step.
// The laptop's own copy (function-registry.json, scripts/vendor-ai-function-registry.mjs) must equal the write part of
// this; the test says so with a clear message when it does not.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const [repo, ref = "HEAD"] = process.argv.slice(2);
if (!repo) {
  console.error("usage: node scripts/vendor-ai-registry-contract.mjs <compliance-tracker checkout> [ref]");
  process.exit(2);
}
const GEN = "supabase/functions/ai-work-link/function-registry.generated.json";
const SPEC = "src/lib/pipeline/function-registry.ts";
const git = (...args) => execFileSync("git", ["-C", repo, ...args], { encoding: "utf8", maxBuffer: 64 << 20 });
const sha = git("rev-parse", ref).trim();
const all = JSON.parse(git("show", `${sha}:${GEN}`));
const specLines = git("show", `${sha}:${SPEC}`).split("\n");

const lineOf = (id) => {
  const exact = specLines.findIndex((l) => l.includes(`functionId: "${id}"`));
  if (exact >= 0) return exact + 1;
  const any = specLines.findIndex((l) => l.includes(`"${id}"`));
  return any >= 0 ? any + 1 : null;
};

const ids = all.map((f) => f.function_id).sort();
const writes = all
  .filter((f) => f.kind === "write")
  .sort((a, b) => a.function_id.localeCompare(b.function_id))
  .map((f) => {
    const line = lineOf(f.function_id);
    const entry = {
      declared: [...f.declared_params].sort(),
      required: f.required_params.map((r) => ({ name: r.name, any_of: [...r.any_of] })),
      min_role_rank: f.min_role_rank,
      money_sensitive: f.money_sensitive,
      link_level: f.link_level,
      excluded: f.excluded_reason !== null,
    };
    return `  // ${SPEC}:${line ?? "?"}\n  ${JSON.stringify(f.function_id)}: ${JSON.stringify(entry)},`;
  });

const out = `// GENERATED by scripts/vendor-ai-registry-contract.mjs -- do not edit by hand; re-run it against a compliance-tracker
// checkout instead. The live AI work link registry's function ids and, for every WRITE, the parameter names the real
// pipeline declares and requires. Each line comment points at the write's own spec in compliance-tracker.
//
// Source: FChecklist/compliance-tracker@${sha}
//   ${GEN}
//   ${SPEC}

export type LiveWrite = {
  declared: string[];
  required: { name: string; any_of: string[] }[];
  min_role_rank: number;
  money_sensitive: boolean;
  link_level: number | null;
  excluded: boolean;
};

export const LIVE_SOURCE_COMMIT = ${JSON.stringify(sha)};

/** Every function id of the live registry (${ids.length} today: reads, asks, runs and writes). */
export const LIVE_FUNCTION_IDS: readonly string[] = ${JSON.stringify(ids)};

/** Every live WRITE (${writes.length} today), by id. */
export const LIVE_WRITES: Readonly<Record<string, LiveWrite>> = {
${writes.join("\n")}
};
`;
const target = join(dirname(fileURLToPath(import.meta.url)), "..", "src/lib/local-first/ai/__fixtures__/live-registry-contract.ts");
writeFileSync(target, out);
console.log(`wrote ${ids.length} ids, ${writes.length} writes from ${sha}`);
