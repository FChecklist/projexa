// Regenerates docs/ERROR_CATALOGUE.md from the typed catalogue. Run: bun scripts/gen-error-catalogue-doc.ts
import { writeFileSync } from "node:fs";
import { SHIPPED_ROUTES } from "../src/lib/nav-routes";
import type { Guide, GuideContext } from "../src/lib/error-guide/types";
import { ALL_GUIDES, CATALOGUE_MODULES } from "../src/lib/error-guide/catalogue/all";
import { genericOnly, mapFixtures } from "../src/lib/error-guide/catalogue/coverage";

const SAMPLE: GuideContext = { route: "/work-progress", search: "?projectId=P1", projectId: "P1", entityId: "E1" };
const cell = (s: string) => s.replace(/\|/g, "/").replace(/\s*\n\s*/g, " ").trim();
const urlOf = (g: Guide) => (!g.fix ? "-" : typeof g.fix.to === "function" ? g.fix.to(SAMPLE) : g.fix.to);
const path = (u: string) => u.split("?")[0]!;
const routePattern = (u: string) => {
  const segs = path(u).split("/").filter(Boolean);
  return SHIPPED_ROUTES.find((p) => { const q = p.split("/").filter(Boolean); return q.length === segs.length && q.every((x, i) => x === segs[i] || x.startsWith("[")); }) ?? path(u);
};

const out: string[] = [];
const screens = new Set<string>();
for (const g of ALL_GUIDES) if (g.fix) screens.add(routePattern(urlOf(g)));
const { unmapped } = mapFixtures();
const generic = genericOnly();

out.push("# PROJEXA error catalogue", "");
out.push("Generated by `bun scripts/gen-error-catalogue-doc.ts` from `src/lib/error-guide/catalogue/*.ts`. Do not edit by hand.", "");
out.push("For every way a real person can get stuck, the screen shows: a short title, a full sentence on what happened, why, numbered steps, a button that goes to the exact place to fix it, and a button that brings them back.", "");
out.push("## Counts", "");
out.push(`- Guides: **${ALL_GUIDES.length}** in **${Object.keys(CATALOGUE_MODULES).length}** modules`);
out.push(`- Distinct in-app screens used as fix destinations: **${screens.size}** (every one checked against the real route list by the test)`);
out.push(`- Real server messages harvested (compliance-tracker + PROJEXA): **${mapFixtures().mapped.size + unmapped.length}**; mapped to a guide: **${mapFixtures().mapped.size}**; unmapped (TODO): **${unmapped.length}**`);
out.push(`- Of the mapped ones, **${generic.length}** are covered only by a general fallback guide (see the last section)`, "");

for (const [name, list] of Object.entries(CATALOGUE_MODULES)) {
  out.push(`## ${name} (${list.length})`, "");
  out.push("| Screen / guide | What the user did wrong or what is missing | What the screen says | Where it takes them | How they come back |");
  out.push("|---|---|---|---|---|");
  for (const g of list) {
    const where = g.fix ? `${g.fix.label}: ${g.fix.where} (${path(urlOf(g))}${g.fix.focus ? ", box: " + g.fix.focus : ""})` : "stays on this screen";
    out.push(`| \`${g.id}\` (${g.source}, ${g.severity}) | ${cell(g.why)} | **${cell(g.title)}.** ${cell(g.what)} Steps: ${g.steps.map((s, i) => `${i + 1}) ${cell(s)}`).join(" ")} | ${cell(where)} | ${cell(g.returnLabel ?? "")} |`);
  }
  out.push("");
}

const codeGuides = ALL_GUIDES.filter((g) => g.match.code && !g.match.messageRegex);
out.push("## Codes the screens must raise (client-side)", "");
out.push("These guides have no server message to read; the screen (or fetch layer) has to pass this `code` in the GuideContext. Until it does, the guide never appears.", "");
out.push("| code | guide | when |", "|---|---|---|");
for (const g of codeGuides) out.push(`| \`${g.match.code}\` | \`${g.id}\` | ${cell(g.why)} |`);
out.push("");

out.push("## TODO: harvested messages with no guide", "");
if (unmapped.length === 0) out.push("None: every harvested message matches at least a general guide.", "");
else for (const u of unmapped) out.push(`- ${u.status ?? "?"} \`${cell(u.message)}\` at ${u.where.join(", ")}`);

out.push("", "## Covered only by a general fallback (candidates for a specific guide)", "");
out.push("These show correct general advice (try again / fill the named box) but not screen-specific wording yet. Mostly `Failed to ...` 500s and bare `x is required` validation.", "");
for (const f of generic) out.push(`- ${f.status ?? "?"} \`${cell(f.message).slice(0, 140)}\` at ${f.where[0]}`);
out.push("");
writeFileSync(new URL("../docs/ERROR_CATALOGUE.md", import.meta.url), out.join("\n"));
console.log("wrote docs/ERROR_CATALOGUE.md", ALL_GUIDES.length, "guides", screens.size, "screens");
